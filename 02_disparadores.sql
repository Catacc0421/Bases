-- Tabla para la auditoría de tarifas
CREATE TABLE auditoria_tarifa (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario VARCHAR2(50),
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP,
    id_habitacion NUMBER,
    id_temporada NUMBER,
    valor_anterior NUMBER(12,2),
    valor_nuevo NUMBER(12,2),
    CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria)
);

-- Disparador de auditoría sobre TARIFA
-- Nota: Aunque pide "nivel de sentencia", para capturar valor anterior y nuevo 
-- es OBLIGATORIO usar FOR EACH ROW en Oracle.
CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
AFTER UPDATE ON tarifa
FOR EACH ROW
BEGIN
    IF :OLD.valor_noche <> :NEW.valor_noche THEN
        INSERT INTO auditoria_tarifa (usuario, id_habitacion, id_temporada, valor_anterior, valor_nuevo)
        VALUES (USER, :NEW.id_habitacion, :NEW.id_temporada, :OLD.valor_noche, :NEW.valor_noche);
    END IF;
END;
/

-- Disparador de fila: Impedir solape de reservas
CREATE OR REPLACE TRIGGER trg_evitar_solape
BEFORE INSERT OR UPDATE ON reserva_habitacion
FOR EACH ROW
DECLARE
    v_conteo NUMBER;
    PRAGMA AUTONOMOUS_TRANSACTION; -- Evita error de tabla mutante al consultar la misma tabla
BEGIN
    SELECT COUNT(*) INTO v_conteo
    FROM reserva_habitacion rh
    JOIN reserva r ON rh.id_reserva = r.id_reserva
    WHERE rh.id_habitacion = :NEW.id_habitacion
      AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
      AND rh.fecha_checkin < :NEW.fecha_checkout
      AND rh.fecha_checkout > :NEW.fecha_checkin
      AND rh.id_reserva_habitacion != NVL(:NEW.id_reserva_habitacion, -1);

    IF v_conteo > 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Trigger: La habitación ya se encuentra ocupada en esas fechas.');
    END IF;
    COMMIT;
END;
